"""Read-only offline correction plan for one completed six-Agent uninstall.

Only explicit external manifest and pinned local Git objects are read. Original
HOME paths remain identities in the snapshot map and are never opened.
"""
import copy
import json
import os
from pathlib import Path
import re
import subprocess
import types

from . import legacy_import as legacy, paths, registry, plugin_release, uninstall, uninstall_memory as memory
from . import uninstall_recovery as recovery
from .layout import RuntimeLayout


def _fail(message):
    raise recovery.Conflict(message)


def _path(value):
    path=Path(value)
    if not path.is_absolute() or os.path.normpath(str(path))!=str(path):_fail('Normalized absolute evidence path required')
    return path


def _git(repo, *args):
    env=dict(os.environ, HOME='/nonexistent', GIT_CONFIG_GLOBAL='/dev/null',
             GIT_CONFIG_NOSYSTEM='1', GIT_OPTIONAL_LOCKS='0', GIT_NO_REPLACE_OBJECTS='1')
    return subprocess.check_output(['git','-C',str(repo),*args],env=env,stderr=subprocess.PIPE)


def _snapshot(value):
    if not isinstance(value,dict):_fail('Invalid snapshot')
    kind=value.get('kind')
    keys={'file':{'kind','hex','mode'},'directory':{'kind','mode'},'absent':{'kind'},'symlink':{'kind','target'}}
    if kind not in keys or set(value)!=keys[kind]:_fail('Unknown snapshot fields')
    if kind in ('file','directory') and (type(value['mode']) is not int or not 0<=value['mode']<=0o7777):_fail('Invalid snapshot mode')
    if kind=='file' and bytes.fromhex(value['hex']).hex()!=value['hex']:_fail('Noncanonical snapshot bytes')
    return copy.deepcopy(value)


def _delete_proven_additions(frozen, native, body, reproduced, spans):
    """Trace old merge slices; delete only generated bytes that it actually added."""
    delimiter=rb'(\r?\n(?:[ \t]*\r?\n)+)'
    present={entry for protected,data in frozen.protected_parts(native,assembled=True) if not protected
             for entry in re.split(delimiter,data)[::2]}
    keeper={data for protected,data in frozen.protected_parts(native,assembled=True) if protected}
    pieces=[];offset=0
    for protected,data in frozen.protected_parts(body,assembled=True):
        if protected:
            if data not in keeper:pieces.append((data,offset));keeper.add(data)
        else:
            parts=re.split(delimiter,data);position=offset
            for index in range(0,len(parts),2):
                entry=parts[index];separator=parts[index+1] if index+1<len(parts) else b''
                if not entry.strip() or entry not in present:
                    pieces.append((entry+separator,position))
                    if entry.strip():present.add(entry)
                position+=len(entry)+len(separator)
        offset+=len(data)
    addition=b''.join(data for data,_ in pieces)
    prefix=native+(b'\n' if native.endswith(b'\n') else b'\n\n')
    if not addition.strip() or prefix+addition!=reproduced:_fail('Old merge trace cannot be reproduced')
    output=[]
    for data,start in pieces:
        cursor=0
        for left,right in sorted(spans):
            lo=max(0,left-start);hi=min(len(data),right-start)
            if lo<hi:output.append(data[cursor:lo]);cursor=hi
        output.append(data[cursor:])
    return prefix+b''.join(output)


def plan_repair(manifest_path, *, manifest_sha256, source_repo, source_commit):
    manifest_path=_path(manifest_path);repo=_path(source_repo)
    if not re.fullmatch(r'[0-9a-f]{40}|[0-9a-f]{64}',source_commit):_fail('Full original source pin required')
    if manifest_path.parent.resolve()!=manifest_path.parent or manifest_path.is_symlink() or not manifest_path.is_file():_fail('Regular external manifest required')
    raw=manifest_path.read_bytes()
    if recovery.digest(raw)!=manifest_sha256:_fail('External manifest digest mismatch')
    envelope=json.loads(raw,object_pairs_hook=registry._no_duplicates)
    registry._keys(envelope,'plan status approval','completed uninstall manifest')
    if envelope['status']!='completed':_fail('Only completed uninstall is eligible')
    plan=envelope['plan'];body=dict(plan);digest=body.pop('plan_sha256',None)
    if digest!=recovery.digest(recovery.encoded(body)) or type(plan.get('schema_version')) is not int or plan['schema_version']!=1:_fail('Uninstall plan hash/schema mismatch')
    if plan.get('command')!='uninstall-machine' or plan.get('memory_return')!='native-direct-v1':_fail('Unsupported old return producer')
    recovery.approve(envelope['approval'],recovery.summary(plan))
    home=_path(plan['home']);runtime=RuntimeLayout(home)
    if manifest_path!=_path(plan['backup_dir'])/'manifest.json' or manifest_path.is_relative_to(home):_fail('External backup identity mismatch')
    if plan.get('user_reference_redirects'):_fail('Redirected native return needs separate offline review')
    config=paths.select_platform(paths.load_agents_table(),'darwin')
    native={a:paths.expand_path(c['user_entry'],home=str(home)) for a,c in config.items()}
    if plan.get('agents')!=list(paths.AGENT_ORDER):_fail('Exactly six proven native recipients required')
    nodes={};changes={}
    for row in plan['changes']:
        name=str(_path(row['path']))
        if name in changes:_fail('Duplicate uninstall output')
        changes[name]=row
        before=_snapshot(row['before']);after=_snapshot(row['after'])
        if row['stage']=='delete_product':
            if after!={'kind':'absent'} or not Path(name).is_relative_to(home):_fail('Invalid product deletion snapshot')
            nodes[name]=before
        elif row['stage']=='detach':
            if not (Path(name).is_relative_to(home) or any(Path(name).is_relative_to(_path(p)) for p in plan.get('project_roots',[]))):_fail('Invalid detach path')
        else:_fail('Unsupported uninstall stage')
    evidence=memory.FusionEvidenceReader(nodes)
    ledger_raw=evidence.read(runtime.registry)
    allowed=set(paths.allowed_user_paths(config,None,home=str(home)))
    ledger=registry.require_installed(registry.validate_registry(json.loads(ledger_raw,object_pairs_hook=registry._no_duplicates),allowed_user_paths=allowed))
    product=ledger['product']
    if product['source']['commit']!=source_commit or plan['installation_id']!=product['installation_id']:_fail('Original source/installation pin mismatch')
    marker=json.loads(evidence.read(runtime.code/'.agm-code-manifest.json'),object_pairs_hook=registry._no_duplicates)
    registry._keys(marker,'product_id source files','snapshot code marker')
    if marker['product_id']!='mem-sharing' or marker['source']!=product['source'] or legacy.digest(legacy.encoded(marker['files']))!=product['source']['tree_sha256']:_fail('Snapshot C/V identity mismatch')
    if _git(repo,'rev-parse',source_commit+'^{commit}').decode().strip()!=source_commit:_fail('Direct source commit required')
    tracked={}
    for item in _git(repo,'ls-tree','-r','-z',source_commit).split(b'\0'):
        if item:
            meta,name=item.split(b'\t');mode,kind,blob=meta.decode().split();tracked[name.decode()]=(mode,kind,blob)
    if {r['path'] for r in marker['files']}!={n for n in tracked if plugin_release.managed_source(n)}:_fail('Pinned managed source set differs from C')
    if recovery.digest(evidence.read(runtime.code/'scripts/agm_core/uninstall_recovery.py'))!=plan['recovery_sha256']:_fail('Original recovery producer mismatch')
    replay_dependencies={'uninstall.py','uninstall_recovery.py','user_entries.py','policy_migration.py',
        'public_layout.py','entries.py','registry.py','transaction.py','paths.py','legacy_import.py','layout.py'}
    old_memory=None;expected_nodes={str(runtime.code),str(runtime.code/'.agm-code-manifest.json')}
    for item in marker['files']:
        registry._keys(item,'path sha256 mode','snapshot code file')
        rel=item['path'];relative=Path(rel)
        if relative.is_absolute() or '..' in relative.parts or str(relative)!=rel:_fail('Unsafe code manifest name')
        target=runtime.code/rel;content=evidence.read(target)
        if recovery.digest(content)!=item['sha256'] or nodes[str(target)]['mode']!=item['mode']:_fail('Snapshot C bytes/mode drift')
        if rel not in tracked:_fail('Source pin missing managed code')
        mode,kind,blob=tracked[rel]
        if kind!='blob' or int(mode,8)&0o777!=item['mode'] or _git(repo,'cat-file','blob',blob)!=content:_fail('Source Git/C bytes or mode mismatch')
        expected_nodes.add(str(target));expected_nodes.update(str(p) for p in target.parents if p.is_relative_to(runtime.code))
        if rel=='scripts/agm_core/uninstall_memory.py':old_memory=content
        elif rel.startswith('scripts/agm_core/') and Path(rel).name in replay_dependencies:
            # Pinned old helper imports are executed only through identical current dependencies.
            current=Path(__file__).parent/Path(rel).name
            if not current.is_file() or current.read_bytes()!=content:_fail('Pinned helper dependency differs from current tool')
    if {n for n in nodes if Path(n).is_relative_to(runtime.code)}!=expected_nodes:_fail('Snapshot C closure mismatch')
    if old_memory is None:_fail('Pinned old memory algorithm missing')
    frozen=types.ModuleType('agm_core._offline_frozen_memory');frozen.__package__='agm_core'
    exec(compile(old_memory,'<verified original uninstall_memory>','exec'),frozen.__dict__)
    if hasattr(frozen,'fusion_generated_units'):_fail('Original producer already has fusion governance classification')
    original={n:v for n,v in nodes.items() if Path(n).is_relative_to(runtime.root/'memories') or Path(n).is_relative_to(runtime.root/'references')}
    old_body=frozen.public_body(runtime,original)
    roots=[_path(p) for p in plan['delete_roots']]
    units=list(ledger['machine']['objects'].values())+list(ledger['shared_objects'].values())
    reproduced_natives=[]
    for agent in paths.AGENT_ORDER:
        name=native[agent];row=changes.get(name)
        if row is None or row['stage']!='detach' or row['before']['kind']!='file' or row['after']['kind']!='file':_fail('Missing native return snapshots')
        before=row['before'];after=row['after']
        if plan['observations'].get(name)!=before:_fail('Native before observation mismatch')
        native_raw=bytes.fromhex(before['hex'])
        if before['mode']!=after['mode']:_fail('Old uninstall changed native mode')
        own=[o for o in units if o['path']==name];imports=[o for o in own if o['kind']=='import']
        if len(imports)>1:_fail('Ambiguous native import')
        for obj in own:
            if uninstall._preserve_ck(obj,roots,native_raw):continue
            if obj['kind']=='import' and obj['ownership']=='reused':
                if recovery.digest(bytes.fromhex(before['hex']))!=obj['fingerprint']['value']:_fail('Old native import observation mismatch')
                token=('@'+str(runtime.root/'memories/MEMORY.md')).encode()
                if native_raw.count(token)!=1 or sum(l.removeprefix(b'\xef\xbb\xbf').strip()==token for l in native_raw.splitlines())!=1:_fail('Old native import ambiguous')
            else:native_raw=uninstall._without_object(native_raw,obj)
        if imports and imports[0]['ownership']=='reused':native_raw=native_raw.replace(('@'+str(runtime.root/'memories/MEMORY.md')).encode(),b'',1)
        native_raw=frozen.retire_legacy_pointer(native_raw,Path(name),proven=False)
        native_raw=frozen.strip_generated(native_raw,runtime,historical_proof=False)
        frozen.require_no_product_dependency(native_raw,roots,home=home,document=Path(name))
        reproduced=frozen.merge_native(native_raw,old_body)
        if reproduced!=bytes.fromhex(after['hex']):_fail('Old native after cannot be reproduced: '+agent)
        identity=plan['native_identities'].get(name)
        if not isinstance(identity,list) or len(identity)!=2 or any(type(n) is not int or n<0 for n in identity):_fail('Native identity missing')
        reproduced_natives.append((agent,name,after,native_raw,reproduced,identity))
    # Do not even calculate corrections until all six old results reproduce.
    new_body=memory.public_body(runtime,original,evidence=evidence)
    units_proven=memory.fusion_generated_units(runtime,original,evidence=evidence)
    spans=[]
    for topic in units_proven:
        for token in (memory.FUSION_GENERATED_PREFIX,('- 用户记忆：'+Path(topic).name+'\n').encode()):
            if old_body.count(token)!=1:_fail('Ambiguous old generated display unit')
            begin=old_body.index(token);spans.append((begin,begin+len(token)))
    outputs=[]
    for agent,name,after,native_raw,reproduced,identity in reproduced_natives:
        corrected=_delete_proven_additions(frozen,native_raw,old_body,reproduced,spans)
        if not corrected.startswith(native_raw):_fail('Correction would alter original native content')
        old_ck=[p for protected,p in memory.protected_parts(reproduced,assembled=True) if protected]
        new_ck=[p for protected,p in memory.protected_parts(corrected,assembled=True) if protected]
        if old_ck!=new_ck:_fail('Correction would alter Context Keeper')
        outputs.append({'agent':agent,'path':name,'before':copy.deepcopy(after),
            'after':{'kind':'file','hex':corrected.hex(),'mode':after['mode']},'native_identity':identity,
            'assertions':{'old_after_reproduced':True,'original_native_preserved':True,'deletion_only':True,'context_keeper_preserved':True,'mode_preserved':True,'inode_must_match_before_write':True}})
    result={'schema_version':1,'command':'repair-fusion-return-offline','status':'plan_only','execution_supported':False,
        'home':str(home),'uninstall_manifest':str(manifest_path),'uninstall_manifest_sha256':manifest_sha256,
        'original_source_commit':source_commit,'uninstall_plan_sha256':digest,'changes':outputs,
        'required_before_execution':'Root must revalidate exact before bytes/mode and original dev/inode under lock; preserve independent recovery evidence.'}
    return recovery.seal(result)
