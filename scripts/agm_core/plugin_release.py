"""Deterministic Paseo payloads and separately approved durable source exports.

Hashes prove integrity, never authorship. Plugin callers must bind the expected
manifest digest in their trusted installed package, not accept it from an RPC.
This module does no network access, activation, migration or runtime install.
"""
import json
import os
import re
import shutil
import stat
import subprocess
import tempfile
from pathlib import Path

from . import legacy_import as legacy, migrate, registry, user_install

OFFICIAL = 'https://github.com/vincent4j/mem-sharing'
SHIPPED_DOCS = ('SKILL.md', 'README.md', 'INSTALL.md', 'llms.txt', 'DESIGN.md',
                'docs/architecture.md', 'docs/operations.md')
ROOT_MANIFEST = 'release/core-release.json'
PAYLOAD = 'plugins/paseo/payload'
IDENTITY = 'plugins/paseo/server/shared/release-identity.ts'


def _identity_bytes(digest):
    return ('// Generated by tools/plugin-release; do not edit.\n'
            "export const CORE_RELEASE_MANIFEST_SHA256 = '"+digest+"';\n").encode('utf-8')


class ReleaseError(ValueError):
    def __init__(self, message, code='release_invalid'):
        super().__init__(message)
        self.code = code


def _fail(message, code='release_invalid'):
    raise ReleaseError(message, code)


def managed_source(name):
    return (name in SHIPPED_DOCS or name.startswith('scripts/')) and name != 'scripts/registry.json' and not name.startswith(('scripts/backups/', 'scripts/.agm.lock/'))


def _path(value):
    p = Path(value)
    if not p.is_absolute() or '..' in p.parts or p != p.resolve():
        _fail('Canonical absolute path required')
    return p


def _git(root, *args):
    return subprocess.run(['git', '-c', 'core.fsmonitor=false', '-C', str(root), *args],
                          capture_output=True, check=True,
                          env=dict(os.environ, GIT_OPTIONAL_LOCKS='0')).stdout


def clean_checkout(root, commit=None):
    root = _path(root)
    if _git(root, 'rev-parse', '--show-toplevel').decode().strip() != str(root):
        _fail('Source must be a repository root', 'source_drift')
    actual = _git(root, 'rev-parse', 'HEAD').decode().strip()
    commit = commit or actual
    if not isinstance(commit, str) or not re.fullmatch(r'[0-9a-f]{40}|[0-9a-f]{64}', commit) or actual != commit:
        _fail('Checkout HEAD must equal full pinned commit', 'source_drift')
    if _git(root, 'status', '--porcelain', '--untracked-files=all').strip():
        _fail('Dirty checkout: preserve it and supply a clean verified source', 'source_drift')
    return root, commit


def _origin(root):
    result = subprocess.run(['git', '-C', str(root), 'config', '--get', 'remote.origin.url'], capture_output=True, text=True)
    return OFFICIAL if result.stdout.strip() in (OFFICIAL, OFFICIAL+'.git',
        'https://github.com/vincent4j/agent-group-memory', 'https://github.com/vincent4j/agent-group-memory.git') else 'local-checkout:'+root.as_uri()


def _git_files(root, commit):
    files = []
    for item in _git(root, 'ls-tree', '-rz', '--full-tree', commit).split(b'\0'):
        if not item:
            continue
        meta, raw_name = item.split(b'\t', 1)
        name = raw_name.decode('utf-8')
        if not managed_source(name):
            continue
        mode, kind, blob = meta.split()
        if kind != b'blob' or mode not in (b'100644', b'100755'):
            _fail('Nonregular tracked product file: '+name, 'source_drift')
        data = _git(root, 'cat-file', 'blob', blob.decode())
        files.append({'path':name, 'sha256':legacy.digest(data), 'mode':int(mode, 8) & 0o777})
    return sorted(files, key=lambda x:x['path'])


def _validate_manifest(value):
    registry._keys(value, 'schema_version product_id source files', 'plugin release')
    if type(value['schema_version']) is not int or value['schema_version'] != 1 or value['product_id'] != 'mem-sharing':
        _fail('Unsupported plugin release')
    source = value['source']
    registry._keys(source, 'url commit version tree_sha256', 'plugin source')
    if source['url'] != OFFICIAL and not (isinstance(source['url'], str) and source['url'].startswith('local-checkout:file:///')):
        _fail('Unsupported source origin')
    if not isinstance(source['commit'], str) or not re.fullmatch(r'[0-9a-f]{40}|[0-9a-f]{64}', source['commit']):
        _fail('Full source pin required')
    if not isinstance(source['version'], str) or not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', source['version']):
        _fail('Explicit release SemVer required')
    files = value['files']
    if not isinstance(files, list) or not files:
        _fail('Closed product file list required')
    names = []
    for item in files:
        registry._keys(item, 'path sha256 mode', 'plugin file')
        name = item['path']; p = Path(name)
        if p.is_absolute() or '..' in p.parts or str(p) != name or not managed_source(name):
            _fail('Unsafe/nonproduct release path')
        registry._digest(item['sha256'])
        if type(item['mode']) is not int or item['mode'] not in (0o644, 0o755):
            _fail('Unsupported product mode')
        names.append(name)
    if names != sorted(set(names)) or not set(SHIPPED_DOCS) <= set(names):
        _fail('Release must contain all seven shipped documents, sorted without duplicates')
    if source['tree_sha256'] != legacy.digest(legacy.encoded(files)):
        _fail('Release tree mismatch')
    return value


def _read_manifest(path, expected=None):
    path = _path(path)
    if not path.is_file():
        _fail('Missing release manifest')
    raw = path.read_bytes()
    if expected is not None:
        registry._digest(expected)
        if legacy.digest(raw) != expected:
            _fail('Manifest differs from package-bound digest', 'source_drift')
    value = _validate_manifest(json.loads(raw))
    if raw != legacy.encoded(value):
        _fail('Release manifest must use canonical JSON')
    return value


def verify_core(root, manifest):
    root = _path(root)
    source = dict(root=str(root), **{k:manifest['source'][k] for k in ('url','commit','version')},
                  files={x['path']:x['sha256'] for x in manifest['files']})
    actual, files = user_install._source({'source':source})
    if files != manifest['files'] or actual['tree_sha256'] != manifest['source']['tree_sha256']:
        _fail('Product bytes/modes differ from release', 'source_drift')
    allowed = set()
    for item in files:
        p = root/item['path']; allowed.add(p)
        allowed.update(p.parents)
    for p in root.rglob('*'):
        if p.is_symlink() or p not in allowed or not (p.is_file() or p.is_dir()):
            _fail('Extra/unsafe payload node', 'source_drift')
    return source


def generate(root, commit, version, output):
    """Build only into a new explicit directory; never edits a checkout."""
    root, commit = clean_checkout(root, commit)
    output = _path(output)
    if os.path.lexists(output) or output.is_relative_to(root):
        _fail('Generation requires an absent output outside source')
    files = _git_files(root, commit)
    manifest = _validate_manifest({'schema_version':1,'product_id':'mem-sharing',
        'source':{'url':_origin(root),'commit':commit,'version':version,
                  'tree_sha256':legacy.digest(legacy.encoded(files))},'files':files})
    # Detect tracked working bytes/modes ignored by Git flags, before generating.
    for item in files:
        p = root/item['path']
        if p != p.resolve() or not p.is_file() or legacy.digest(p.read_bytes()) != item['sha256'] or stat.S_IMODE(p.stat().st_mode) != item['mode']:
            _fail('Working product differs from pinned source', 'source_drift')
    output.mkdir(mode=0o700)
    for item in files:
        target = output/PAYLOAD/'core'/item['path']
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((root/item['path']).read_bytes()); target.chmod(item['mode'])
    for name in (ROOT_MANIFEST, PAYLOAD+'/release.json'):
        target = output/name; target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(legacy.encoded(manifest)); target.chmod(0o644)
    digest = legacy.digest(legacy.encoded(manifest))
    identity = output/IDENTITY; identity.parent.mkdir(parents=True, exist_ok=True)
    identity.write_bytes(_identity_bytes(digest)); identity.chmod(0o644)
    verify_core(output/PAYLOAD/'core', manifest)
    return {'manifest_sha256':digest, 'manifest':manifest}


def checkout_delivery(root, commit, version=None):
    root, commit = clean_checkout(root, commit)
    tracked = set(_git(root, 'ls-files', '-z').decode().split('\0'))
    if ROOT_MANIFEST not in tracked:
        _fail('No tracked release descriptor')
    for name in (ROOT_MANIFEST, PAYLOAD+'/release.json'):
        if name not in tracked or (root/name) != (root/name).resolve() or not (root/name).is_file():
            _fail('Release descriptors must be tracked regular files', 'source_drift')
        if (root/name).read_bytes() != _git(root, 'cat-file', 'blob', commit+':'+name):
            _fail('Working release descriptor differs from R', 'source_drift')
    manifest = _read_manifest(root/ROOT_MANIFEST)
    if version is not None and version != manifest['source']['version']:
        _fail('Requested version differs from release', 'source_drift')
    source_commit = manifest['source']['commit']
    _git(root, 'merge-base', '--is-ancestor', source_commit, commit)
    if _origin(root) != manifest['source']['url']:
        _fail('Release origin differs from checkout origin', 'source_drift')
    if _git_files(root, source_commit) != manifest['files'] or _git_files(root, commit) != manifest['files']:
        _fail('S/R managed set/bytes/modes differ', 'source_drift')
    changes = _git(root, 'diff', '--name-only', '-z', source_commit, commit).decode().split('\0')
    for name in filter(None, changes):
        if name != ROOT_MANIFEST and not name.startswith((PAYLOAD+'/', 'plugins/paseo/dist/', 'plugins/paseo/server/shared/')):
            _fail('R changes nongenerated source: '+name, 'source_drift')
    for item in manifest['files']:
        p = root/item['path']
        if p != p.resolve() or not p.is_file() or legacy.digest(p.read_bytes()) != item['sha256'] or stat.S_IMODE(p.stat().st_mode) != item['mode']:
            _fail('Checkout product differs from S/R', 'source_drift')
        if PAYLOAD+'/core/'+item['path'] not in tracked:
            _fail('Untracked release payload', 'source_drift')
    expected = legacy.digest((root/ROOT_MANIFEST).read_bytes())
    identity = root/IDENTITY
    if (IDENTITY not in tracked or identity != identity.resolve() or not identity.is_file()
            or identity.read_bytes() != _identity_bytes(expected)
            or identity.read_bytes() != _git(root, 'cat-file', 'blob', commit+':'+IDENTITY)):
        _fail('Missing/drifted generated package identity constant', 'source_drift')
    _read_manifest(root/PAYLOAD/'release.json', expected)
    verify_core(root/PAYLOAD/'core', manifest)
    return {'kind':'git-checkout','root':str(root),'commit':commit,'version':manifest['source']['version']}


def inspect_delivery(delivery):
    if delivery.get('kind') == 'git-checkout':
        registry._keys(delivery, 'kind root commit version', 'checkout delivery')
        checkout_delivery(delivery['root'], delivery['commit'], delivery['version'])
        payload = Path(delivery['root'])/PAYLOAD
        manifest = _read_manifest(payload/'release.json')
    elif delivery.get('kind') == 'plugin-package':
        # The package containing this pinned digest is the caller's trust root.
        # A supplied digest/pin alone is explicitly NOT a verified host origin.
        registry._keys(delivery, 'kind payload manifest_sha256', 'plugin delivery')
        payload = _path(delivery['payload'])
        manifest = _read_manifest(payload/'release.json', delivery['manifest_sha256'])
    else:
        _fail('Unsupported delivery kind')
    if set(p.name for p in payload.iterdir()) != {'core','release.json'}:
        _fail('Payload envelope is not closed', 'source_drift')
    source = verify_core(payload/'core', manifest)
    return manifest, source


def _export_source(destination, manifest):
    source = verify_core(destination/'core', manifest)
    expected = {'source-manifest.json':legacy.encoded(source), 'release.json':legacy.encoded(manifest)}
    if set(p.name for p in destination.iterdir()) != {'core', 'acquisition.json', *expected}:
        _fail('Foreign node in durable export', 'source_drift')
    for name, raw in expected.items():
        p = destination/name
        if p.is_symlink() or not p.is_file() or p.read_bytes() != raw or stat.S_IMODE(p.stat().st_mode) != 0o600:
            _fail('Durable export receipt drift', 'source_drift')
    receipt_path = destination/'acquisition.json'
    if receipt_path.is_symlink() or not receipt_path.is_file() or stat.S_IMODE(receipt_path.stat().st_mode) != 0o600:
        _fail('Missing/unsafe export acquisition receipt', 'source_drift')
    receipt = json.loads(receipt_path.read_bytes())
    registry._keys(receipt, 'plan approval', 'source acquisition receipt')
    saved = receipt['plan']; body = dict(saved); digest = body.pop('plan_sha256')
    migrate._approval(saved, receipt['approval'])
    if (digest != legacy.digest(legacy.encoded(body)) or saved['manifest'] != manifest
            or saved['destination'] != str(destination) or saved['command'] != 'prepare-release-source'):
        _fail('Export acquisition identity drift', 'source_drift')
    return source


def plan_export(delivery, home, operation_id):
    home = _path(home)
    if not home.is_dir():
        _fail('Existing HOME required')
    migrate._op(operation_id)
    manifest, source = inspect_delivery(delivery)
    destination = home/'.local/share/mem-sharing-sources'/manifest['source']['version']/manifest['source']['tree_sha256']
    user_install._real_chain(destination, home)
    exists = os.path.lexists(destination)
    if exists:
        _export_source(destination, manifest)
    plan = {'schema_version':1,'command':'prepare-release-source','operation_id':operation_id,
        'home':str(home),'delivery':delivery,'manifest':manifest,'source':source,
        'destination':str(destination),'reused':exists,
        'source_trust':'clean-pinned-checkout' if delivery['kind']=='git-checkout' else 'caller-trusted-package-required',
        'changes':[] if exists else [{'path':str(destination),'operation':'durable_product_export'}]}
    plan['plan_sha256'] = legacy.digest(legacy.encoded(plan))
    return plan


def export_result(plan):
    destination = Path(plan['destination'])
    source = _export_source(destination, plan['manifest'])
    return {'status':'acquired','installation_complete':False,'source':source,
            'source_manifest':str(destination/'source-manifest.json'),
            'acquisition_manifest':str(destination/'acquisition.json'),
            'reused':plan['reused'], 'source_trust':plan['source_trust']}


def execute_export(plan, approval):
    migrate._approval(plan, approval)
    current = plan_export(plan['delivery'], plan['home'], plan['operation_id'])
    if current != plan:
        _fail('Export plan drift; preview again', 'approval_mismatch')
    home = Path(plan['home'])
    # Source asset lock only; never enters or replaces product business locks.
    with migrate._lock(home/'.mem-sharing-source.lock', plan):
        if plan_export(plan['delivery'], plan['home'], plan['operation_id']) != plan:
            _fail('Locked export scene drift', 'source_drift')
        if plan['reused']:
            return export_result(plan)
        destination = Path(plan['destination'])
        destination.parent.mkdir(parents=True, mode=0o700, exist_ok=True)
        stage = Path(tempfile.mkdtemp(prefix='.prepare-', dir=str(destination.parent)))
        try:
            for item in plan['manifest']['files']:
                raw = (Path(plan['source']['root'])/item['path']).read_bytes()
                if legacy.digest(raw) != item['sha256']:
                    _fail('Source drift while exporting', 'source_drift')
                target = stage/'core'/item['path']; target.parent.mkdir(parents=True, exist_ok=True)
                migrate._put(target, raw, item['mode'])
            source = dict(plan['source'], root=str(destination/'core'))
            migrate._put(stage/'source-manifest.json', legacy.encoded(source), 0o600)
            migrate._put(stage/'release.json', legacy.encoded(plan['manifest']), 0o600)
            migrate._put(stage/'acquisition.json', legacy.encoded({'plan':plan,'approval':approval}), 0o600)
            verify_core(stage/'core', plan['manifest'])
            # Revalidate source and target immediately before the atomic publish.
            if plan_export(plan['delivery'], plan['home'], plan['operation_id']) != plan:
                _fail('Export scene changed before publish', 'source_drift')
            os.rename(stage, destination); migrate._sync_directory(destination.parent)
            return export_result(plan)
        finally:
            if stage.exists():
                shutil.rmtree(stage)
